export function buildUserPrompt({ message, state, memories, lessons }) {
  return [
    'Current Charon state:',
    JSON.stringify(state, null, 2).slice(0, 9000),
    '',
    'Recent memories:',
    JSON.stringify(memories || [], null, 2).slice(0, 2500),
    '',
    'Recent lessons:',
    JSON.stringify(lessons || [], null, 2).slice(0, 2500),
    '',
    `User message: ${message}`,
  ].join('\n');
}

